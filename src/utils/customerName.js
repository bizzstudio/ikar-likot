// שם הלקוח של הזמנה, כפי שהוא מוצג למלקט.
//
// המקור הוא תמיד user_info — הצילום שנשמר על ההזמנה בעת ביצועה — ולא כרטיס
// הלקוח: זו ההזמנה הזו, וגם רשימת ההזמנות ממילא אינה מאכלסת (populate) את
// הלקוח. שני חלקי השם אופציונליים בסכמה (models/Order.js), כך שהזמנת אורח
// עשויה להגיע בלי שם משפחה, ובמקרי קצה בלי שם כלל.
//
// מרוכז כאן ולא נכתב בכל מסך מחדש: שלושה מסכים מציגים את אותו שם — רשימת
// ההזמנות באיסוף עצמי, תצוגה מקדימה של הזמנה ומסך הליקוט עצמו — ושם שמוצג
// אחרת בכל אחד מהם הופך את זיהוי הלקוח שהגיע לחנות לבדיוק מה שהוא לא אמור
// להיות: ניחוש.
//
// הפונקציה מחזירה את **המקור בעברית**. התרגום לשפת המלקט הוא שלב נפרד
// (tPerson ב-src/i18n/DynamicTranslation.jsx), ומכוון שיקרה בזמן הרינדור.

/**
 * שם מלא של לקוח ההזמנה, או מחרוזת ריקה כשאין.
 * ערך שאינו מחרוזת (מסמך פגום, אובייקט שהוזרק) נספר כחסר ולא כ-"[object Object]".
 * @param {object} order הזמנה כפי שהיא מגיעה מהשרת
 * @returns {string}
 */
export const customerFullName = (order) =>
  [order?.user_info?.name, order?.user_info?.lastName]
    .map((part) => (typeof part === "string" ? part.trim() : ""))
    .filter(Boolean)
    .join(" ");
