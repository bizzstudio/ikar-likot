export const getWord = (word) => {
  const { language } = useContext(languageContext);
  // נפילה חיננית לעברית אם השפה השמורה אינה קיימת (למשל "india" ישן שהוחלף בתאית)
  const dict = LA[language] || LA.hebrew;
  return <>{dict[word]}</>;
};

export const getWordString = (lang, key) => LA[lang]?.[key] ?? LA.hebrew?.[key] ?? key;

export default function Language({ setOpenMenu }) {
  const { setLanguage } = useContext(languageContext);
  const onClick = (e) => {
    setLanguage(e.target.value);
    localStorage.setItem("language", e.target.value);
    setOpenMenu((prev) => !prev);
  };

  const languageOptions = [
    {
      label: "עברית",
      onClick: () => onClick({ target: { value: "hebrew" } })
    },
    {
      label: "ไทย",
      onClick: () => onClick({ target: { value: "thai" } })
    },
    {
      label: "english",
      onClick: () => onClick({ target: { value: "en" } })
    }
  ];

  return (
    <div className="z-20">
      <DropdownMenu
        // title="Language"
        options={languageOptions}
      />
    </div>
  );
}
